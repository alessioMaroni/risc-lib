#!/usr/bin/env perl
use strict;
use warnings;
use Getopt::Long;
use JSON::PP;

my $core = "undefined";
my $xlen = 0;
my $out  = "";
my $in   = "csrs.json";

GetOptions(
    "core=s" => \$core,
    "xlen=i" => \$xlen,
    "out=s"  => \$out,
    "in=s"   => \$in,
) or die "Error, unable to read CMake arguments!\n";

print "[PERL] Configuration: {core: $core, xlen: $xlen, input: $in}\n";

if (!$out) {
    die "Error: output file path (--out) is required!\n";
}

open(my $json_fh, '<', $in) or die "Error: cannot open input file $in: $!\n";
my $json_text = do { local $/; <$json_fh> };
close($json_fh);

my $data = decode_json($json_text);

open(my $fh, '>', $out) or die "Error: cannot open $out: $!\n";
print $fh "/* Auto-generated by csrs.pl - Core: $core, XLEN: $xlen */\n";
print $fh "#ifndef RISCV_CSR_CONFIG_H\n";
print $fh "#define RISCV_CSR_CONFIG_H\n\n";
print $fh "#include <riscv/riscv_xlen.h>\n\n";

if ($data->{enums} && ref($data->{enums}) eq 'ARRAY') {
    foreach my $enum (@{ $data->{enums} }) {
        print $fh "typedef enum\n{\n";
        my @vals = @{ $enum->{values} };
        for (my $i = 0; $i < scalar(@vals); $i++) {
            my $v     = $vals[$i];
            my $comma = ($i < $#vals) ? "," : " ";
            my $comm  = $v->{comment} ? " /* $v->{comment} */" : "";
            printf $fh "    %-18s = %s%s%s\n", $v->{name}, $v->{value}, $comma, $comm;
        }
        print $fh "} $enum->{name};\n\n";
    }
}

# 2. Genera indirizzi CSR, SHIFT e MASK
foreach my $csr (@{ $data->{csrs} }) {
    my $csr_name = $csr->{name};
    my $csr_addr = $csr->{address};
    my $csr_xlen = $csr->{xlen} // "all";
    my $csr_core = $csr->{core} // "none";

    my $xlen_match = (lc($csr_xlen) eq "all" || "$csr_xlen" eq "$xlen");
    my $core_match = (lc($csr_core) eq "none" || lc($csr_core) eq "all" || $csr_core eq $core);

    next unless ($xlen_match && $core_match);

    my $macro_csr = uc($csr_name);
    print $fh "/* ==========================================================================\n";
    print $fh " * CSR: $csr_name ($csr_addr)\n";
    print $fh " * ========================================================================== */\n";
    print $fh "#define __${macro_csr}_CSR ${csr_addr}U\n\n";

    if ($csr->{fields} && ref($csr->{fields}) eq 'ARRAY') {
        foreach my $field (@{ $csr->{fields} }) {
            my $f_xlen = $field->{xlen} // "all";
            my $f_core = $field->{core} // "none";

            next unless (lc($f_xlen) eq "all" || "$f_xlen" eq "$xlen");
            next unless (lc($f_core) eq "none" || lc($f_core) eq "all" || $f_core eq $core);

            my $f_name   = uc($field->{name});
            my $msb      = $field->{msb};
            my $lsb      = $field->{lsb};
            my $width    = $msb - $lsb + 1;
            my $raw_mask = (1 << $width) - 1;

            if ($field->{comment}) {
                print $fh "/* $field->{comment} */\n";
            }
            printf $fh "#define ${macro_csr}_${f_name}_SHIFT %dU\n", $lsb;
            printf $fh "#define ${macro_csr}_${f_name}_MASK  ((riscv_xlen_t)0x%XU << ${macro_csr}_${f_name}_SHIFT)\n\n", $raw_mask;
        }
    }
}

print $fh "#endif /* RISCV_CSR_CONFIG_H */\n";
close($fh);