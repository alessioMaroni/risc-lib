#!/usr/bin/env perl
use strict;
use warnings;
use Getopt::Long;

use constant XLEN_32 => 32;
use constant XLEN_64 => 64;

my $core = "undefined";
my $xlen = 0;
my $out  = "";

GetOptions(
    "core=s" => \$core,
    "xlen=i" => \$xlen,
    "out=s"  => \$out,
) or die "Error, unable to read CMake arguments!\n";

print "[PERL] Configuration: {core: $core, xlen: $xlen}\n";

if (!$out) {
    die "Error: output file path (--out) is required!\n";
}

open(my $fh, '>', $out) or die "Error: cannot open $out: $!\n";
print $fh "/* Auto-generated by csrs.pl - Core: $core, XLEN: $xlen */\n";
print $fh "#ifndef RISCV_CSR_CONFIG_H\n";
print $fh "#define RISCV_CSR_CONFIG_H\n\n";

print $fh "#define __MSTATUS_CSR 0x300U\n\n";

print $fh "#endif /* RISCV_CSR_CONFIG_H */\n";
close($fh);